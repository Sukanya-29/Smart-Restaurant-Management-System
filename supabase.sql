DROP TABLE IF EXISTS tables CASCADE;

-- =========================================================
-- 1. TABLES CREATION
-- =========================================================

CREATE TABLE IF NOT EXISTS tables (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_number INT NOT NULL UNIQUE,
    capacity INT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('available','occupied','reserved'))
);

CREATE TABLE IF NOT EXISTS menu_items (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN ('Starters','Main Course','Beverages','Desserts')),
    price NUMERIC(10,2) NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    prep_time_mins INT NOT NULL,
    dietary_type TEXT NOT NULL CHECK (dietary_type IN ('Veg','Non-Veg','Jain')),
    image_url TEXT,
    model_3d_url TEXT
);

CREATE TABLE IF NOT EXISTS inventory (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name TEXT NOT NULL,
    current_stock NUMERIC(10,2),
    unit TEXT NOT NULL CHECK (unit IN ('kg','liters','packets')),
    reorder_level NUMERIC(10,2),
    cost_per_unit NUMERIC(10,2)
);

CREATE TABLE IF NOT EXISTS staff (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('Manager','Head Chef','Waiter')),
    shift_status TEXT NOT NULL CHECK (shift_status IN ('On Duty','Off Duty'))
);

CREATE TABLE IF NOT EXISTS orders (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id INT REFERENCES tables(id) ON DELETE CASCADE,
    customer_name TEXT,
    customer_phone TEXT,
    total_amount NUMERIC(10,2),
    status TEXT NOT NULL CHECK (status IN ('pending','preparing','ready','served','completed')),
    payment_status TEXT NOT NULL CHECK (payment_status IN ('unpaid','paid')),
    payment_method TEXT NOT NULL CHECK (payment_method IN ('UPI','Cash','Card')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS order_items (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INT REFERENCES orders(id) ON DELETE CASCADE,
    menu_item_id INT REFERENCES menu_items(id),
    quantity INT NOT NULL,
    price_at_time NUMERIC(10,2)
);

