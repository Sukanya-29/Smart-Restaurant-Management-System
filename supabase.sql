-- SERVICE REQUESTS TABLE
-- ==========================================

DROP TABLE IF EXISTS service_requests CASCADE;

CREATE TABLE service_requests (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    table_no TEXT NOT NULL,
    customer_name TEXT NOT NULL,
    service TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Pending',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    accepted_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ
);

-- ==========================================
-- ENABLE RLS
-- ==========================================

ALTER TABLE service_requests
ENABLE ROW LEVEL SECURITY;

-- ==========================================
-- POLICIES
-- ==========================================

CREATE POLICY "Anyone can insert requests"
ON service_requests
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

CREATE POLICY "Anyone can read requests"
ON service_requests
FOR SELECT
TO anon, authenticated
USING (true);

CREATE POLICY "Anyone can update requests"
ON service_requests
FOR UPDATE
TO anon, authenticated
USING (true);

CREATE POLICY "Anyone can delete requests"
ON service_requests
FOR DELETE
TO anon, authenticated
USING (true);

-- ==========================================
-- INDEXES
-- ==========================================

CREATE INDEX idx_service_status
ON service_requests(status);

CREATE INDEX idx_service_created
ON service_requests(created_at);

